/** 「(5.6.9)」 에서 번호를 뽑아 이름으로 바꾼다 */
export function 알레르기풀이(번호글) {
  return String(번호글 || '')
    .split('.')
    .map((n) => n.trim())
    .filter(Boolean)
    .map((n) => ({ 번호: Number(n), 이름: 알레르기표[Number(n)] || '(모르는 번호)' }));
}

/**
 * 식단 한 줄에서 이름과 알레르기 번호를 가른다.
 *   「치킨마요덮밥*-고 (1.2.5.6.13.15)」 → { 이름:'치킨마요덮밥*-고', 번호:'1.2.5.6.13.15' }
 * ⚠ 번호가 없는 반찬도 많다. 그때 번호는 빈 글자다.
 */
export function 반찬가르기(한줄) {
  const 글 = String(한줄 || '').trim();
  const m = /^(.*?)\s*\(([\d.\s]+)\)\s*$/.exec(글);
  if (!m) return { 이름: 글, 번호: '' };
  return { 이름: m[1].trim(), 번호: m[2].replace(/\s/g, '') };
}

/** 「<br/>」로 이어 붙은 식단을 반찬 목록으로 가른다 */
export function 식단가르기(식단글) {
  return String(식단글 || '')
    .split(/<br\s*\/?>/i)
    .map((s) => s.trim())
    .filter(Boolean);
}

