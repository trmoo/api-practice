/**
 * 주소를 조각으로 나눈다.
 *   https://open.neis.go.kr/hub/schoolInfo?Type=json&pSize=5
 *   └프로토콜┘  └───호스트───┘└──경로───┘ └────쿼리스트링────┘
 *
 * 돌려주는 것 = { 성공, 프로토콜, 호스트, 경로, 쿼리[[이름,값]…], 조각글 }
 * 잘못된 주소여도 죽지 않고 성공:false 로 돌려준다.
 */
export function 주소분해(주소) {
  const 글 = String(주소 || '').trim();
  const m = /^([a-zA-Z][a-zA-Z0-9+.-]*):\/\/([^/?#]*)([^?#]*)(?:\?([^#]*))?(?:#(.*))?$/.exec(글);
  if (!m) {
    return { 성공: false, 프로토콜: '', 호스트: '', 경로: '', 쿼리: [], 해시: '', 원문: 글 };
  }
  const [, 프로토콜, 호스트, 경로, 쿼리글, 해시] = m;
  return {
    성공: true,
    프로토콜,
    호스트,
    경로: 경로 || '/',
    쿼리: 쿼리분해(쿼리글 || ''),
    쿼리글: 쿼리글 || '',
    해시: 해시 || '',
    원문: 글,
  };
}

/** 「a=1&b=2」를 [[a,1],[b,2]] 로. 값이 없는 것(&flag)도 받아 준다. */
export function 쿼리분해(쿼리글) {
  if (!쿼리글) return [];
  return 쿼리글.split('&').filter(Boolean).map((한쌍) => {
    const 자리 = 한쌍.indexOf('=');
    if (자리 < 0) return [한쌍, ''];
    return [한쌍.slice(0, 자리), 한쌍.slice(자리 + 1)];
  });
}

/** [[a,1],[b,2]] 를 「a=1&b=2」로. 값은 퍼센트 인코딩한다. */
export function 쿼리조립(쌍들) {
  return 쌍들
    .filter(([이름]) => 이름 !== '' && 이름 !== null && 이름 !== undefined)
    .map(([이름, 값]) => `${이름}=${encodeURIComponent(값 ?? '')}`)
    .join('&');
}

/** 밑주소와 파라미터로 온전한 주소를 만든다. */
export function 주소조립(밑주소, 쌍들) {
  const q = 쿼리조립(쌍들);
  return q ? `${밑주소}?${q}` : 밑주소;
}

/**
 * 퍼센트 인코딩을 한 글자씩 풀어 보여 준다 — 「왜 한글이 %ED%99%8D 이 되나」.
 * 돌려주는 것 = [{ 글자, 바뀐것, 바뀌었나, 바이트[] }]
 */
export function 인코딩낱낱이(글) {
  return [...String(글 || '')].map((글자) => {
    const 바뀐것 = encodeURIComponent(글자);
    const 바이트 = [...new TextEncoder().encode(글자)];
    return {
      글자,
      바뀐것,
      바뀌었나: 바뀐것 !== 글자,
      바이트,
      // 「한」 → EC 95 88 처럼 16진수로도 보여 준다
      십육진: 바이트.map((b) => b.toString(16).toUpperCase().padStart(2, '0')),
    };
  });
}

/**
 * 주소를 안전하게 풀어 읽는다. 잘못된 %xx 가 섞여 있어도 죽지 않는다.
 * (학생이 손으로 주소를 고치다 「%」 하나만 남기는 일이 잦다.)
 */
export function 안전하게풀기(글) {
  try {
    return decodeURIComponent(글);
  } catch {
    return 글;
  }
}

