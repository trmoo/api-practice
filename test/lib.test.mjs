import {
  주소분해, 쿼리분해, 쿼리조립, 주소조립, 인코딩낱낱이, 안전하게풀기, 뜻찾기,
} from '../src/lib/url.js';
import {
  경로글, 값꺼내기, 경로같나, 잎경로모으기, 값종류, 값요약,
} from '../src/lib/json.js';
import { 식단가르기, 반찬가르기, 알레르기풀이 } from '../src/data/quiz.js';

export const 이름 = '주소·경로·전처리';

export function run(T) {
  T.group('주소 분해');
  const 나이스 = 주소분해('https://open.neis.go.kr/hub/schoolInfo?Type=json&pSize=5&SCHUL_NM=와우');
  T.ok('성공', 나이스.성공, true);
  T.ok('프로토콜', 나이스.프로토콜, 'https');
  T.ok('호스트', 나이스.호스트, 'open.neis.go.kr');
  T.ok('경로', 나이스.경로, '/hub/schoolInfo');
  T.ok('파라미터 세 개', 나이스.쿼리.length, 3);
  T.ok('첫 파라미터', 나이스.쿼리[0], ['Type', 'json']);
  T.ok('셋째 파라미터', 나이스.쿼리[2], ['SCHUL_NM', '와우']);

  const 경로없음 = 주소분해('https://dog.ceo');
  T.ok('경로가 없으면 /', 경로없음.경로, '/');
  T.ok('쿼리가 없으면 빈 배열', 경로없음.쿼리, []);

  T.group('주소 분해 — 잘못된 것도 죽지 않는다');
  T.ok('빈 글자', 주소분해('').성공, false);
  T.ok('프로토콜이 없으면', 주소분해('open.neis.go.kr/hub').성공, false);
  T.ok('그냥 글자', 주소분해('안녕하세요').성공, false);
  T.ok('null 도 죽지 않는다', 주소분해(null).성공, false);
  T.ok('undefined 도 죽지 않는다', 주소분해(undefined).성공, false);

  T.group('쿼리 분해 — 별난 경우');
  T.ok('빈 쿼리', 쿼리분해(''), []);
  T.ok('값 없는 파라미터', 쿼리분해('a=1&flag&b=2'), [['a', '1'], ['flag', ''], ['b', '2']]);
  T.ok('값에 = 이 들어 있으면 첫 = 에서만 가른다',
    쿼리분해('q=a=b'), [['q', 'a=b']]);
  T.ok('빈 칸은 건너뛴다', 쿼리분해('a=1&&b=2'), [['a', '1'], ['b', '2']]);

  T.group('쿼리 조립');
  T.ok('보통', 쿼리조립([['a', '1'], ['b', '2']]), 'a=1&b=2');
  T.ok('한글은 인코딩된다', 쿼리조립([['SCHUL_NM', '와우']]), 'SCHUL_NM=%EC%99%80%EC%9A%B0');
  T.ok('이름이 비면 빠진다', 쿼리조립([['', '1'], ['b', '2']]), 'b=2');
  T.ok('값이 없으면 빈 값으로', 쿼리조립([['a', null]]), 'a=');
  T.ok('아무것도 없으면 빈 글자', 쿼리조립([]), '');
  T.ok('주소 조립', 주소조립('https://x.kr/a', [['q', '1']]), 'https://x.kr/a?q=1');
  T.ok('파라미터가 없으면 ? 도 안 붙는다', 주소조립('https://x.kr/a', []), 'https://x.kr/a');

  T.group('한글 인코딩 — 학생에게 보여 주는 값');
  const 와 = 인코딩낱낱이('와');
  T.ok('한 글자', 와.length, 1);
  T.ok('한글은 UTF-8 3바이트', 와[0].바이트.length, 3);
  T.ok('십육진으로 EC 99 80', 와[0].십육진, ['EC', '99', '80']);
  T.ok('주소에는 %EC%99%80', 와[0].바뀐것, '%EC%99%80');
  T.ok('바뀌었다고 표시한다', 와[0].바뀌었나, true);
  const 에이 = 인코딩낱낱이('a');
  T.ok('영문은 그대로', 에이[0].바뀐것, 'a');
  T.ok('영문은 안 바뀌었다고 표시', 에이[0].바뀌었나, false);
  T.ok('영문은 1바이트', 에이[0].바이트.length, 1);
  T.ok('「와우」 전체', 인코딩낱낱이('와우').map((c) => c.바뀐것).join(''), '%EC%99%80%EC%9A%B0');
  T.ok('빈 글자도 죽지 않는다', 인코딩낱낱이(''), []);

  T.group('안전하게 풀기 — 학생이 주소를 잘못 고쳐도');
  T.ok('제대로 된 것', 안전하게풀기('%EC%99%80%EC%9A%B0'), '와우');
  T.ok('% 하나만 남아도 죽지 않는다', 안전하게풀기('%'), '%');
  T.ok('반쪽짜리도 죽지 않는다', 안전하게풀기('%EC%9'), '%EC%9');
  T.ok('그냥 글자는 그대로', 안전하게풀기('abc'), 'abc');

  T.group('파라미터 뜻풀이');
  T.truthy('pSize 는 뜻이 있다', 뜻찾기('pSize'));
  T.has('pSize 뜻에 5건 이야기가 있다', 뜻찾기('pSize'), '5건');
  T.truthy('SCHUL_NM 은 뜻이 있다', 뜻찾기('SCHUL_NM'));
  T.ok('모르는 것은 빈 글자', 뜻찾기('없는파라미터'), '');

  T.group('경로 글 적기');
  const 경로 = ['mealServiceDietInfo', 1, 'row', 0, 'DDISH_NM'];
  T.ok('자바스크립트', 경로글(경로, 'js'), '데이터.mealServiceDietInfo[1].row[0].DDISH_NM');
  T.ok('파이썬', 경로글(경로, 'py'),
    '데이터["mealServiceDietInfo"][1]["row"][0]["DDISH_NM"]');
  T.ok('뿌리 이름을 바꿀 수 있다', 경로글(['a'], 'js', 'd'), 'd.a');
  T.ok('빈 경로는 뿌리만', 경로글([], 'js'), '데이터');
  T.ok('점으로 못 쓰는 이름은 대괄호로',
    경로글(['한글키'], 'js'), '데이터["한글키"]');
  T.ok('숫자로 시작하는 이름도 대괄호로',
    경로글(['1a'], 'js'), '데이터["1a"]');

  T.group('값 꺼내기');
  const 자료 = { a: [{ b: '값' }], n: 3, z: null };
  T.ok('깊이 들어간 값', 값꺼내기(자료, ['a', 0, 'b']), '값');
  T.ok('얕은 값', 값꺼내기(자료, ['n']), 3);
  T.ok('null 도 그대로', 값꺼내기(자료, ['z']), null);
  T.ok('없는 길은 undefined', 값꺼내기(자료, ['a', 5, 'b']), undefined);
  T.ok('null 을 지나가도 죽지 않는다', 값꺼내기(자료, ['z', 'x', 'y']), undefined);
  T.ok('빈 경로는 통째로', 값꺼내기(자료, []), 자료);

  T.group('경로 견주기');
  T.ok('같으면 참', 경로같나(['a', 0], ['a', 0]), true);
  T.ok('길이가 다르면 거짓', 경로같나(['a'], ['a', 0]), false);
  T.ok('다르면 거짓', 경로같나(['a', 0], ['a', 1]), false);
  T.ok('숫자와 글자 「0」은 같게 본다', 경로같나(['a', 0], ['a', '0']), true);
  T.ok('배열이 아니면 거짓', 경로같나(null, ['a']), false);

  T.group('잎 경로 모으기');
  const 잎들 = 잎경로모으기({ a: { b: 1 }, c: [2, 3] });
  T.ok('잎 세 개 — a.b · c[0] · c[1]', 잎들.length, 3);
  T.ok('첫 잎의 경로', 잎들[0].경로, ['a', 'b']);
  T.ok('목록 잎의 경로', 잎들[1].경로, ['c', 0]);
  T.ok('값도 함께 온다', 잎들.map((x) => x.값), [1, 2, 3]);

  T.group('값 종류·요약');
  T.ok('문자열', 값종류('가'), '문자열');
  T.ok('숫자', 값종류(1), '숫자');
  T.ok('참거짓', 값종류(true), '참거짓');
  T.ok('null', 값종류(null), 'null');
  T.ok('목록', 값종류([]), '목록');
  T.ok('객체', 값종류({}), '객체');
  T.ok('문자열 요약에 따옴표', 값요약('가'), '"가"');
  T.ok('목록 요약에 개수', 값요약([1, 2, 3]), '[ … 3개 ]');
  T.ok('객체 요약에 개수', 값요약({ a: 1 }), '{ … 1개 }');
  T.ok('긴 글은 잘린다', 값요약('가'.repeat(60), 10).length <= 12, true);

  T.group('식단 가르기 — <br/> 로 이어 붙은 것');
  const 식단 = '발아현미밥-고 <br/>보리새우얼갈이수제비* (5.6.9)<br/>비름나물무침 (5.6)';
  T.ok('세 가지로 갈린다', 식단가르기(식단).length, 3);
  T.ok('앞뒤 빈칸이 없어진다', 식단가르기(식단)[0], '발아현미밥-고');
  T.ok('<br> 도 갈린다', 식단가르기('가<br>나').length, 2);
  T.ok('<BR/> 대문자도 갈린다', 식단가르기('가<BR/>나').length, 2);
  T.ok('<br /> 빈칸이 있어도 갈린다', 식단가르기('가<br />나').length, 2);
  T.ok('빈 글자는 빈 목록', 식단가르기(''), []);
  T.ok('<br/> 이 없으면 하나', 식단가르기('밥').length, 1);

  T.group('반찬 가르기 — 이름과 알레르기 번호');
  T.ok('번호가 있는 것', 반찬가르기('보리새우얼갈이수제비* (5.6.9)'),
    { 이름: '보리새우얼갈이수제비*', 번호: '5.6.9' });
  T.ok('번호가 없는 것', 반찬가르기('발아현미밥-고'),
    { 이름: '발아현미밥-고', 번호: '' });
  T.ok('번호가 한 개', 반찬가르기('우유 (2)'), { 이름: '우유', 번호: '2' });
  T.ok('빈칸이 섞여 있어도', 반찬가르기('김치 (5. 6)'), { 이름: '김치', 번호: '5.6' });
  // ⚠ 괄호가 이름의 일부인 반찬도 있다. 숫자가 아니면 이름으로 둔다.
  T.ok('숫자가 아닌 괄호는 이름의 일부', 반찬가르기('밥(찰현미)'),
    { 이름: '밥(찰현미)', 번호: '' });

  T.group('알레르기 번호 풀이');
  T.ok('5.6.9 는 콩·밀·새우', 알레르기풀이('5.6.9').map((a) => a.이름),
    ['대두(콩)', '밀', '새우']);
  T.ok('하나만', 알레르기풀이('2').map((a) => a.이름), ['우유']);
  T.ok('빈 글자는 빈 목록', 알레르기풀이(''), []);
  T.ok('모르는 번호는 알려 준다', 알레르기풀이('99')[0].이름, '(모르는 번호)');
  T.ok('번호도 함께 온다', 알레르기풀이('5.6')[0].번호, 5);
}
